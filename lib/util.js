// Человеческий анкор из сырого ключа: «задние тормозные колодки киа рио 3» → «Задние тормозные колодки Kia Rio 3»
const CYR_TO_LAT = { 'рио': 'Rio', 'сид': 'Ceed', 'селтос': 'Seltos', 'спортейдж': 'Sportage',
  'соренто': 'Sorento', 'оптима': 'Optima', 'черато': 'Cerato', 'серато': 'Cerato',
  'пиканто': 'Picanto', 'соул': 'Soul', 'стингер': 'Stinger', 'карнивал': 'Carnival',
  'мохав': 'Mohave', 'спектра': 'Spectra', 'венга': 'Venga', 'стоник': 'Stonic', 'ниро': 'Niro' }

export function prettifyKey(key) {
  if (!key) return ''
  let t = (' ' + key.trim() + ' ').replace(/ киа /gi, ' Kia ')
  for (const [cyr, lat] of Object.entries(CYR_TO_LAT)) {
    t = t.replace(new RegExp(' ' + cyr + ' ', 'gi'), ' ' + lat + ' ')
  }
  t = t.replace(/\s+/g, ' ').trim()
  return t.charAt(0).toUpperCase() + t.slice(1)
}
